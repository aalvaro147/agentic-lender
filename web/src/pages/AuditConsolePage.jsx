/* AI audit console for one application (E4).
   Stories: WEB-36 (generated credit memorandum, shown in full).
   WEB-32 to WEB-35 (agent outputs, committee decision, decision trails, model per agent)
   wait for per-agent output from the AI engine, so they are a labelled placeholder (D7).
   Same access as the loan file: another broker's application looks like an unknown ID (D5). */

import { Link, useParams } from 'react-router'
import { useAuth } from '../auth/useAuth'
import { ROLES } from '../auth/roles'
import { useApplication } from '../hooks/useApplication'
import { StatusBadge } from '../components/Badges'
import { SectionPlaceholder } from '../components/LoanFileSections'
import { EMPTY, formatDate } from '../utils/format'

export function AuditConsolePage() {
  const { id } = useParams() // the :id part of /applications/:id/audit
  const { role } = useAuth()
  const pipelineLabel = role === ROLES.BROKER ? 'My clients' : 'Pipeline'
  const { loading, file, error } = useApplication(id)

  const breadcrumb = (
    <nav aria-label="Breadcrumb" className="text-sm text-muted">
      <Link to="/pipeline" className="text-brand underline hover:text-brand-dark">
        {pipelineLabel}
      </Link>{' '}
      /{' '}
      {file ? (
        <Link
          to={`/applications/${id}`}
          className="font-mono text-brand underline hover:text-brand-dark"
        >
          {id}
        </Link>
      ) : (
        <span className="font-mono">{id}</span>
      )}{' '}
      / AI audit
    </nav>
  )

  if (loading) {
    return (
      <div className="flex flex-col gap-6">
        {breadcrumb}
        <p role="status" className="text-muted">
          Loading application…
        </p>
      </div>
    )
  }

  if (error) {
    return (
      <div className="flex flex-col gap-6">
        {breadcrumb}
        <p role="alert" className="rounded-md bg-risk-high-bg px-3 py-2 text-sm text-risk-high">
          {error}
        </p>
      </div>
    )
  }

  // D5: unknown ID and another broker's application end here in the same way
  if (!file) {
    return (
      <div className="flex flex-col gap-6">
        {breadcrumb}
        <div className="rounded-lg border border-line bg-white p-8 text-center">
          <h1 className="text-2xl font-semibold">Application not found</h1>
          <p className="mt-2 text-muted">
            There is no application {id}, or it is not available to you.
          </p>
          <Link
            to="/pipeline"
            className="mt-6 inline-block font-medium text-brand hover:text-brand-dark"
          >
            Back to {pipelineLabel.toLowerCase()}
          </Link>
        </div>
      </div>
    )
  }

  const memo = file.creditMemo

  return (
    <div className="flex flex-col gap-6">
      {breadcrumb}

      <header>
        <h1 className="text-3xl font-semibold">AI audit console</h1>
        <div className="mt-2 flex flex-wrap items-center gap-2 text-sm text-muted">
          <span>{file.borrowerName ?? EMPTY}</span>
          <StatusBadge status={file.status} />
        </div>
      </header>

      {/* WEB-36: the memo is shown in full, with its line breaks, never shortened */}
      <section
        aria-label="Credit memorandum"
        className="rounded-lg border border-line bg-white p-6"
      >
        <h2 className="text-xl font-semibold">Credit memorandum</h2>
        {memo ? (
          <>
            <p className="mt-1 text-sm text-muted">
              Generated by the AI engine ({memo.modelVersion ?? EMPTY}) on{' '}
              {formatDate(memo.generatedAt)}
              {memo.isMock && (
                <span className="ml-2 rounded-full bg-page px-2 py-0.5 text-xs font-medium">
                  Mock AI output
                </span>
              )}
            </p>
            <p className="mt-4 leading-relaxed whitespace-pre-wrap">{memo.text}</p>
          </>
        ) : (
          <p className="mt-2 text-muted">
            No credit memo yet. It appears here once the AI has assessed this application.
          </p>
        )}
      </section>

      <SectionPlaceholder
        title="Agent committee"
        story="WEB-32 to WEB-35"
        description="Each agent's output, the committee decision, the decision trail per agent and the model used. Waiting for per-agent output from the AI engine."
      />
    </div>
  )
}
