/* WEB-36: credit memorandum on the AI audit console */

import { describe, it, expect } from 'vitest'
import { render, screen, within } from '@testing-library/react'
import { MemoryRouter, Route, Routes } from 'react-router'
import { AuthContext } from '../auth/AuthContext'
import { AuditConsolePage } from './AuditConsolePage'
import mockApplications from '../mocks/applications.json'

const orla = { uid: 'mock-underwriter-01', role: 'underwriter', displayName: 'Orla Hennessy' }
const ciaran = { uid: 'mock-broker-01', role: 'broker', displayName: "Ciarán O'Neill" }

const memoOf = (applicationId) =>
  mockApplications.find((a) => a.applicationId === applicationId).aiAssessment.creditMemo

function openAs(profile, applicationId) {
  return render(
    <AuthContext.Provider
      value={{ user: { uid: profile.uid }, profile, role: profile.role, loading: false }}
    >
      <MemoryRouter initialEntries={[`/applications/${applicationId}/audit`]}>
        <Routes>
          <Route path="/applications/:id/audit" element={<AuditConsolePage />} />
        </Routes>
      </MemoryRouter>
    </AuthContext.Provider>,
  )
}

describe('AuditConsolePage (WEB-36)', () => {
  it('shows the credit memo text in full', async () => {
    openAs(orla, 'AL-2026-0148')
    const memo = await screen.findByRole('region', { name: 'Credit memorandum' })

    expect(within(memo).getByText(memoOf('AL-2026-0148'))).toBeInTheDocument()
  })

  it('says which model produced the memo, when, and that it is mock output', async () => {
    openAs(orla, 'AL-2026-0148')
    const memo = await screen.findByRole('region', { name: 'Credit memorandum' })

    expect(within(memo).getByText(/Generated by the AI engine \(mock-0\.2\)/)).toBeInTheDocument()
    expect(within(memo).getByText('Mock AI output')).toBeInTheDocument()
  })

  it('shows the borrower and status, with links back to the pipeline and the loan file', async () => {
    openAs(orla, 'AL-2026-0148')
    await screen.findByRole('heading', { name: 'AI audit console' })

    expect(screen.getByText('Aoife Murphy')).toBeInTheDocument()
    expect(screen.getByText('AI Deliberated')).toBeInTheDocument()
    const breadcrumb = screen.getByRole('navigation', { name: 'Breadcrumb' })
    expect(within(breadcrumb).getByRole('link', { name: 'Pipeline' })).toHaveAttribute(
      'href',
      '/pipeline',
    )
    expect(within(breadcrumb).getByRole('link', { name: 'AL-2026-0148' })).toHaveAttribute(
      'href',
      '/applications/AL-2026-0148',
    )
  })

  it('explains that there is no memo before the AI has run', async () => {
    openAs(orla, 'AL-2026-0146') // APPLIED, no aiAssessment
    const memo = await screen.findByRole('region', { name: 'Credit memorandum' })

    expect(within(memo).getByText(/No credit memo yet/)).toBeInTheDocument()
  })

  it('shows a labelled placeholder for the agent committee (WEB-32 to WEB-35, D7)', async () => {
    openAs(orla, 'AL-2026-0148')
    const committee = await screen.findByRole('region', { name: 'Agent committee' })

    expect(within(committee).getByText('Coming in WEB-32 to WEB-35')).toBeInTheDocument()
  })

  it("shows a broker their own client's memo", async () => {
    openAs(ciaran, 'AL-2026-0148') // Ciaran's client
    const memo = await screen.findByRole('region', { name: 'Credit memorandum' })

    expect(within(memo).getByText(memoOf('AL-2026-0148'))).toBeInTheDocument()
    expect(screen.getByRole('link', { name: 'My clients' })).toBeInTheDocument()
  })

  it("treats another broker's application like an unknown ID (D5)", async () => {
    openAs(ciaran, 'AL-2026-0147') // Emma's client
    expect(
      await screen.findByRole('heading', { name: 'Application not found' }),
    ).toBeInTheDocument()
    expect(screen.queryByRole('region', { name: 'Credit memorandum' })).not.toBeInTheDocument()
  })

  it('shows "Application not found" for an unknown ID', async () => {
    openAs(orla, 'AL-2026-9999')
    expect(
      await screen.findByRole('heading', { name: 'Application not found' }),
    ).toBeInTheDocument()
  })
})
